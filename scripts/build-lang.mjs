import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_LOCALES, LANGUAGE_CATALOG } from "./languages.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const langDir = path.join(root, "assets", "ssc_bw", "lang");
const cobblemonLangDir = path.join(root, "assets", "cobblemon", "lang");
const dataDir = path.join(root, "data");
const dataFile = path.join(dataDir, "all-data.json");

const uiLocales = fs.readdirSync(langDir)
  .filter((name) => name.endsWith(".json"))
  .map((name) => name.slice(0, -".json".length));
const locales = [...DEFAULT_LOCALES];
for (const locale of uiLocales) {
  if (!locales.includes(locale)) locales.push(locale);
}
const LANGUAGES = locales.map((locale) => {
  const meta = LANGUAGE_CATALOG[locale] || {
    id: locale.replace(/_/g, "-"),
    label: locale,
    tag: locale.replace(/_/g, "-"),
  };
  return { ...meta, locale };
});

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
}

function normalizeSuffix(text) {
  const raw = String(text || "").toLowerCase().trim();
  const aliases = {
    "mega-x": "megax",
    "mega y": "megay",
    "mega-y": "megay",
    "mega x": "megax",
    "g-max": "gmax",
    "gmax": "gmax",
    "alolan": "alola",
    "galarian": "galar",
    "hisuian": "hisui",
    "paldean": "paldea",
    "alola": "alola",
    "galar": "galar",
    "hisui": "hisui",
    "paldea": "paldea",
  };
  if (aliases[raw]) return aliases[raw];
  return raw.replace(/[^a-z0-9]+/g, "");
}

const FORM_LABEL_FALLBACKS = {
  zh_cn: { totem: "霸主", bustedtotem: "霸主·现形" },
  en_us: { totem: "Totem", bustedtotem: "Busted Totem" },
  ko_kr: { totem: "토템", bustedtotem: "토템·들킨 모습" },
};

const enFile = path.join(langDir, "en_us.json");
if (!fs.existsSync(enFile)) {
  console.error(`[ERROR] missing language file: ${enFile}`);
  process.exit(1);
}

const en = readJson(enFile);
const enKeys = new Set(Object.keys(en));
const lang = { en_us: en };
const reports = [];

for (const language of LANGUAGES) {
  if (language.locale === "en_us") continue;
  const file = path.join(langDir, `${language.locale}.json`);
  if (!fs.existsSync(file)) {
    reports.push(`${language.locale}: missing UI file, English fallback`);
    continue;
  }
  const table = readJson(file);
  const keys = new Set(Object.keys(table));
  const unknown = [...keys].filter((key) => !enKeys.has(key));
  if (unknown.length) {
    console.error(`[ERROR] unknown keys in ${language.locale}.json: ${unknown.join(", ")}`);
    process.exit(1);
  }
  const missing = [...enKeys].filter((key) => !keys.has(key));
  lang[language.locale] = table;
  reports.push(
    missing.length
      ? `${language.locale}: ${missing.length} keys fall back to English`
      : `${language.locale}: complete`
  );
}

const data = readJson(dataFile);
const names = {};

for (const language of LANGUAGES) {
  const file = path.join(cobblemonLangDir, `${language.locale}.json`);
  if (!fs.existsSync(file)) {
    reports.push(`pokemon.${language.locale}: missing, English fallback`);
    continue;
  }
  const cobblemon = readJson(file);
  const table = {};
  for (const pokemon of data.pokemon) {
    if (!pokemon.isForm) {
      table[pokemon.id] =
        cobblemon[`cobblemon.species.${pokemon.id}.name`] ||
        pokemon.name.en ||
        pokemon.id;
      continue;
    }

    const baseName =
      table[pokemon.baseId] ||
      cobblemon[`cobblemon.species.${pokemon.baseId}.name`] ||
      pokemon.name.en ||
      pokemon.id;
    const suffix = normalizeSuffix(pokemon.formName);
    const region = /^(alola|galar|hisui|paldea)/i.exec(pokemon.formName || "");
    const fallback = FORM_LABEL_FALLBACKS[language.locale] || FORM_LABEL_FALLBACKS.en_us;
    const formLabel =
      cobblemon[`cobblemon.ui.pokedex.info.form.${pokemon.baseId}-${suffix}`] ||
      cobblemon[`cobblemon.ui.pokedex.info.form.${suffix}`] ||
      (region ? cobblemon[`cobblemon.ui.pokedex.info.form.${region[1].toLowerCase()}`] : "") ||
      fallback[suffix] ||
      "";
    const lowerBase = baseName.toLowerCase();
    const lowerLabel = formLabel.toLowerCase();
    const isChinese = ["zh_cn", "zh_hk", "zh_tw"].includes(language.locale);
    if (formLabel && lowerBase && lowerLabel.includes(lowerBase)) {
      table[pokemon.id] = formLabel;
    } else if (formLabel) {
      table[pokemon.id] = isChinese ? `${baseName}（${formLabel}）` : `${baseName} (${formLabel})`;
    } else {
      table[pokemon.id] = pokemon.name[language.locale] || pokemon.name.en || pokemon.id;
    }
  }
  names[language.locale] = table;
}

const out = `/* Generated by scripts/build-lang.mjs. Do not edit by hand. */\n` +
  `window.SSC_BW_LANGUAGES = ${JSON.stringify(LANGUAGES)};\n` +
  `window.SSC_BW_LANG = ${JSON.stringify(lang)};\n`;
fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(path.join(dataDir, "lang.js"), out, "utf8");

const namesOut = `/* Generated by scripts/build-lang.mjs. Do not edit by hand. */\n` +
  `window.SUNLIT_POKEMON_NAMES = ${JSON.stringify(names)};\n`;
fs.writeFileSync(path.join(dataDir, "pokemon-names.js"), namesOut, "utf8");

console.log(`[lang] ${Object.keys(lang).join(", ")} (${enKeys.size} UI keys)`);
for (const report of reports) console.log(`[i18n] ${report}`);
console.log(`[pokemon] ${Object.keys(names).length} locales`);
console.log(`[out] ${path.join(dataDir, "lang.js")}`);
console.log(`[out] ${path.join(dataDir, "pokemon-names.js")}`);
